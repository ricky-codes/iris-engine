-- O motor não guarda nada por pedido: sem pedidos, chamadas ao modelo nem resultados.
-- "Ação" passa a "ferramenta". Os utilizadores só são criados por um administrador.

-- ---------- pedidos e resultados: saem ----------

DROP TABLE sentiment_signal, tipification_result_value, tipification_result,
           reply_result, reply_request, sentiment_result, llm_call, inference_request;
DROP FUNCTION tipification_value_check_tenant();
DROP FUNCTION llm_call_check_prompt_action();

-- Listas fechadas que só serviam os pedidos e os resultados.
DROP TABLE request_status, error_type, sentiment_label, urgency_level, message_item_type;

-- Os dados pessoais deixam de ser guardados, por isso não há retenção a configurar.
ALTER TABLE tenant DROP COLUMN result_retention_days;

-- ---------- ação -> ferramenta ----------

ALTER TABLE action RENAME TO tool;
ALTER TABLE tool RENAME COLUMN action_id TO tool_id;
ALTER TABLE tool RENAME CONSTRAINT action_pkey TO tool_pkey;
ALTER TABLE tool RENAME CONSTRAINT action_code_key TO tool_code_key;
ALTER TABLE tool RENAME CONSTRAINT action_code_check TO tool_code_check;

-- As ferramentas vivem no código: o motor regista-as aqui ao arrancar, por isso o id
-- passa a ser gerado e deixa de haver "implementada ou não".
ALTER TABLE tool DROP COLUMN is_implemented;
ALTER TABLE tool ALTER COLUMN tool_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('tool', 'tool_id'), (SELECT max(tool_id) FROM tool));

ALTER TABLE memory_action RENAME TO memory_tool;
ALTER TABLE memory_tool RENAME COLUMN action_id TO tool_id;
ALTER TABLE memory_tool RENAME CONSTRAINT memory_action_pkey TO memory_tool_pkey;
ALTER TABLE memory_tool RENAME CONSTRAINT memory_action_memory_id_fkey TO memory_tool_memory_id_fkey;
ALTER TABLE memory_tool RENAME CONSTRAINT memory_action_action_id_fkey TO memory_tool_tool_id_fkey;

ALTER TABLE tenant_action_config RENAME TO tenant_tool_config;
ALTER TABLE tenant_tool_config RENAME COLUMN action_id TO tool_id;
ALTER TABLE tenant_tool_config RENAME CONSTRAINT tenant_action_config_pkey TO tenant_tool_config_pkey;
ALTER TABLE tenant_tool_config
  RENAME CONSTRAINT tenant_action_config_tenant_id_fkey TO tenant_tool_config_tenant_id_fkey;
ALTER TABLE tenant_tool_config
  RENAME CONSTRAINT tenant_action_config_action_id_fkey TO tenant_tool_config_tool_id_fkey;
ALTER TABLE tenant_tool_config
  RENAME CONSTRAINT tenant_action_config_llm_model_id_fkey TO tenant_tool_config_llm_model_id_fkey;
ALTER TABLE tenant_tool_config
  RENAME CONSTRAINT tenant_action_config_max_output_tokens_check TO tenant_tool_config_max_output_tokens_check;
ALTER TABLE tenant_tool_config
  RENAME CONSTRAINT tenant_action_config_temperature_check TO tenant_tool_config_temperature_check;
ALTER TABLE tenant_tool_config
  RENAME CONSTRAINT tenant_action_config_timeout_ms_check TO tenant_tool_config_timeout_ms_check;

ALTER TABLE prompt RENAME COLUMN action_id TO tool_id;
ALTER TABLE prompt RENAME CONSTRAINT prompt_action_id_fkey TO prompt_tool_id_fkey;
ALTER TABLE prompt RENAME CONSTRAINT prompt_action_id_tenant_id_key TO prompt_tool_id_tenant_id_key;

-- "Conhecimento" ainda não existe: sai do catálogo se ninguém o usa.
DELETE FROM tool t
WHERE t.code = 'knowledge'
  AND NOT EXISTS (SELECT 1 FROM prompt p WHERE p.tool_id = t.tool_id)
  AND NOT EXISTS (SELECT 1 FROM tenant_tool_config c WHERE c.tool_id = t.tool_id)
  AND NOT EXISTS (SELECT 1 FROM memory_tool m WHERE m.tool_id = t.tool_id);

-- ---------- utilizadores: criados por um administrador ----------

ALTER TABLE org_user RENAME COLUMN first_seen_at TO created_at;
